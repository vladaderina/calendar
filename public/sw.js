// Пустой сервис-воркер. Нужен ровно для одного: без него Chrome на Android
// не предлагает «Установить приложение», а создаёт обычную закладку, и иконка
// с домашнего экрана берётся не из manifest.json.
//
// ВАЖНО: здесь НЕТ кеширования ни на байт. Кеширующий воркер пинит старый
// бандл, и телефон неделями работает на старой версии приложения — это уже
// случалось. Пустой fetch-обработчик даёт установку без этого риска.
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', () => {
  // Ничего не перехватываем: запрос уходит в сеть как обычно.
});
